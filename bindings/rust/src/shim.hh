#pragma once

// Thin C++ shim adapting detent::Client to types cxx (the Rust FFI bridge,
// see ../src/lib.rs) supports directly across the boundary (primitive
// types, rust::Str/String/Vec, UniquePtr, and exceptions-as-Result) -- no
// evaluation/parsing logic of its own, same scope as the Python binding.
//
// This header is included!()'d directly into cxx's *generated* lib.rs.h,
// hoisted to the very top of that file (before cxx's own generated
// rust::Str/rust::Vec/etc. definitions and before HealthInfo's generated
// definition) -- so it must NOT include the generated lib.rs.h itself
// (that circular include silently breaks type visibility for everything
// declared here) and must only *forward-declare* HealthInfo, not use its
// full definition. shim.cc, a normal leaf translation unit with no such
// ordering constraint, includes the generated header directly to get
// HealthInfo's real definition for health()'s implementation.
#include "rust/cxx.h"

#include "detent/client.hh"

#include <cstdint>
#include <memory>

namespace detent_rust {

struct HealthInfo; // full definition generated by cxx from lib.rs's shared struct

// The opaque type cxx's bridge (lib.rs) only ever sees as `ClientHandle`
// (via UniquePtr<ClientHandle> and const ClientHandle&) -- the generated
// bridge glue (lib.rs.cc) needs this to be a *complete* type wherever it
// includes this header, hence the full definition living here.
class ClientHandle {
public:
	explicit ClientHandle(detent::InitOptions opts) : client_(std::move(opts)) {}
	detent::Client client_;
};

std::unique_ptr<ClientHandle> new_client(
	rust::Str defaults_path, bool has_source_path, rust::Str source_path,
	rust::Vec<rust::String> cli_overrides, std::int32_t poll_interval_ms);

bool eval(const ClientHandle& client, rust::Str name, bool has_hash, rust::Str hash_val, bool has_switch,
          rust::Str switch_val);

std::int64_t get_int(const ClientHandle& client, rust::Str name, bool has_switch, rust::Str switch_val);

HealthInfo health(const ClientHandle& client) noexcept;

} // namespace detent_rust
